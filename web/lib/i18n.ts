export const dict = { vi, en };
export type Lang = keyof typeof dict;

/** Replace `{key}` tokens in a template string with values from `vars`. */
export function tf(str: string, vars?: Record<string, string | number>): string {
  if (!vars) return str;
  return str.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
}

/** Current-language dictionary + the raw language code + a setter. */
export function useT() {
  const lang = useStore((s) => s.lang);
  const setLang = useStore((s) => s.setLang);
  return { t: dict[lang], lang, setLang };
}
